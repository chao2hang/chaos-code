#!/usr/bin/env python3
"""Ledger of every test that a platform `cfg` keeps out of a build, and what that costs.

Why this exists rather than a comment in a review: `#[ignore]` has an inventory
(`scripts/ci/ignored-tests.py`, which refuses an ignored test without a reason), but a test
behind `#[cfg(unix)]` had none, and it is skipped just as completely -- more so, because it is not
even compiled, so no runner reports it as skipped. On 2026-10-03 the first full Windows leg made
that concrete: a family of persistent-shell assertions went red on `windows-latest`, and the pass
that turned the leg green did it by putting `#[cfg(unix)]` on eleven of them. The suite went green
without any behaviour being fixed, and nothing in the repository could afterwards say which tests
had been gated for that reason or what stopped being executed there.

This script produces the inventory and refuses five kinds of drift:

  * a gated test with no ledger row (new gating, needs a reason before it can merge);
  * a ledger row whose site is gone, or whose platform set, non-platform `cfg`, or marker set
    changed (the row was edited out from under the test, or the test was rewritten under it);
  * a row without a real reason, or one still carrying the import marker once the unreviewed
    budget (`--max-unreviewed`) is spent;
  * more platform-blind files than `--max-blind-windows` / `--max-blind-macos` allow;
  * more gated tests with no platform assumption in them than `--max-assumption-free` allows, with
    the offending tests named on stderr (`--list-assumption-free` prints the list on its own).

A file is blind for a platform if it contains at least one platform-gated test and no test at all
that would run on that platform -- so `#[cfg(unix)]` tests in a file with no Windows-capable test
leave that file executing nothing on Windows, and the two caps hold that count down. All four
numbers are checked, not merely printed, so they can only move down.

The platform set of a test is the intersection of every `cfg` that applies to it, not just the
attribute on the `fn`: a `#[cfg(unix)] mod tests { ... }` gates everything inside it, and a file
starting `#![cfg(unix)]` gates the whole file. Non-platform `cfg` (features) does not narrow the
platform set but is recorded in its own column, because a test gated on both is hidden behind two
independent switches.

The `assumptions` column answers the question the debt note asked: which gated tests are not about
the platform they are gated to. It lists the POSIX (or Windows) things visible inside the test body
and in the name of the file holding it, and `none` means none were found, which makes the row worth
naming. A row is identified by that column too, so the ledger cannot keep an old claim after a test
gains or loses a marker. The line number is the one column that is not part of a row's identity: it
is a navigation hint regenerated by `--write-baseline`, because otherwise every edit made above a
gated test would demand a rewrite whose diff says nothing.

Stated limits, because each one is a way for new gating to look ordinary:

  * `cfg` expressions are read as written on the item. `cfg_attr(...)` is understood only in the
    `cfg_attr(<platform>, ignore = "...")` shape, counted as a test that exists on that platform
    and does not run there; any other `cfg_attr` is invisible here.
  * `cfg` applied by a macro (`include!`, a custom test-attribute macro) is invisible.
  * a file pulled in by a platform-gated `mod` declaration does not inherit that gate here, so a
    file compiled only on unix reads as ungated. The scan covers every `.rs` file in the
    repository except `target/`, `.git/`, `node_modules/`, `dist/` and `test-results/`; members
    outside `crates/` are scanned, so nothing cargo builds is graded by a narrower walk.
  * `cfg(not(unix))` counts as covering `other` as well as `windows`, because that is what it
    covers. Nothing here claims any runner executed anything: the ledger records what the source
    excludes, which is not the same fact and is not a substitute for the platform legs.
  * a `none` in `assumptions` is a claim about the test's own text. It is wrong in two known ways:
    the assumption may sit inside a helper the test calls (calls are not followed), or inside the
    production code under test. Markers are therefore broad and portable spellings are left out;
    `none` says a test is worth a look, not that it would pass elsewhere.

    scripts/ci/platform-gated-tests.py                       # the summary
    scripts/ci/platform-gated-tests.py --table               # every ledger row
    scripts/ci/platform-gated-tests.py --list-assumption-free  # gates with nothing to gate
    scripts/ci/platform-gated-tests.py --write-baseline scripts/ci/platform-gated-tests.tsv
    scripts/ci/platform-gated-tests.py --check-baseline scripts/ci/platform-gated-tests.tsv \
        --max-unreviewed N --max-blind-windows N --max-blind-macos N --max-assumption-free N
"""

