def path_words(rel: str) -> frozenset[str]:
    return frozenset(w for w in re.split(r"[^a-z0-9]+", rel.lower()) if w)


def assumption_label(body: str, runs_on: frozenset[str], words: frozenset[str]) -> str:
    """The platform assumptions visible in one test body and in the name of the file holding it.

    Only the families the test's own gating keeps out are considered: a unix-only test is asked
    what POSIX thing it needs, a Windows-only test what Windows thing it needs. `none` means
    neither family appeared, which is what makes the row worth naming.
    """
    missing = ALL_PLATFORMS - runs_on
    labels: list[str] = []
    if missing & {"windows", "other"}:
        labels += [name for name, rx in POSIX_ASSUMPTION if rx.search(body)]
        if words & POSIX_PATH_WORDS:
            labels.append("file-name")
    if missing & {"linux", "macos", "other-unix"}:
        labels += [name for name, rx in WINDOWS_ASSUMPTION if rx.search(body)]
        if words & WINDOWS_PATH_WORDS:
            labels.append("file-name")
    return ";".join(sorted(set(labels))) or "none"


def blank_noise(text: str, keep_strings: bool = False) -> str:
    """Blank comments and string literals, keeping every character position.

    Line numbers in the ledger have to be the ones an editor takes you to, so nothing here shifts
    offsets. Positions are what the caller uses: attribute *content* is sliced out of the raw text
    at the offsets found here, because blanking erases the `"macos"` in `cfg(target_os = "macos")`
    while leaving the attribute's position alone. A `#[cfg(unix)]` written in a comment or a string
    literal has no live `#` in the blanked copy, so it is not a gate.

    `keep_strings=True` leaves string contents alone while still blanking comments, which is what
    the platform-assumption markers want: `Command::new("chmod")` and `"/tmp/x"` are assumptions,
    and a `chmod` mentioned only in a doc comment is not.
    """
    out = list(text)
    i = 0
    n = len(text)
    depth = 0
    while i < n:
        if depth:
            if text.startswith("*/", i):
                depth -= 1
                out[i] = out[i + 1] = " "
                i += 2
                continue
            if text[i] != "\n":
                out[i] = " "
            i += 1
            continue
        # Everything between two interesting characters is copied through untouched, so the scan
        # jumps to the next one instead of stepping over it. Without this the pass is a per-character
        # Python loop over every line of Rust in the repository, and the gate stops being runnable.
        jump = NOISE.search(text, i)
        if jump is None:
            break
        i = jump.start()
        if text.startswith("/*", i):
            depth += 1
            out[i] = out[i + 1] = " "
            i += 2
            continue
        if text.startswith("//", i):
            while i < n and text[i] != "\n":
                out[i] = " "
                i += 1
            continue
        raw = RAW_STRING.match(text, i)
        if raw:
            terminator = '"' + "#" * len(raw.group(1))
            start = raw.end()
            end = text.find(terminator, start)
            stop = n if end < 0 else end + len(terminator)
            if not keep_strings:
                for k in range(i, min(stop, n)):
                    if text[k] != "\n":
                        out[k] = " "
            i = max(stop, i + 1)
            continue
        if text[i] == '"':
            j = i + 1
            while j < n and text[j] not in "\n\"":
                j += 2 if text[j] == "\\" else 1
            if not keep_strings:
                for k in range(i, min(j + 1, n)):
                    if text[k] != "\n":
                        out[k] = " "
            i = max(j + 1, i + 1)
            continue
        if text[i] == "'":
            literal = CHAR_LITERAL.match(text, i)
            if literal:
                for k in range(i, literal.end()):
                    out[k] = " "
                i = literal.end()
                continue
        i += 1
    return "".join(out)


def split_top(expr: str) -> list[str]:
    """Split a comma-separated cfg argument list at depth one."""
    parts: list[str] = []
    depth = 0
    current: list[str] = []
    for ch in expr:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append("".join(current))
            current = []
            continue
        current.append(ch)
    if "".join(current).strip():
        parts.append("".join(current))
    return parts


def atom_platforms(name: str, value: str | None) -> frozenset[str] | None:
    """Platforms an `ident` / `ident = "value"` cfg selects, or None if it is not about platforms.

    None means "this says nothing about the platform": it must not narrow anything, and the caller
    records it in `extra_cfg`. An unrecognised `target_os` value returns None on purpose, so a
    spelling this file does not know shows up in the `extra_cfg` column for a human to read rather
    than silently selecting nothing.
    """
    if name == "unix":
        return UNIXISH
    if name == "windows":
        return frozenset({"windows"})
    if name == "target_os" and value is not None:
        if value not in TARGET_OS:
            return None
        return frozenset(TARGET_OS[value])
    if name == "target_family" and value is not None:
        if value == "unix":
            return UNIXISH
        if value == "windows":
            return frozenset({"windows"})
    return None


def eval_cfg(expr: str) -> tuple[frozenset[str], list[str]]:
    """Evaluate a cfg expression into (platforms it selects, terms that are not platforms)."""
    platforms = ALL_PLATFORMS
    extra: list[str] = []
    for part in split_top(expr):
        part = part.strip()
        if not part:
            continue
        combinator = COMBINATOR.match(part)
        if combinator:
            kind, inner = combinator.group(1), combinator.group(2)
            if kind == "not":
                sub, sub_extra = eval_cfg(inner)
                platforms &= ALL_PLATFORMS - sub
                extra += sub_extra
                continue
            if kind == "all":
                # `all(a, b)` intersects, and eval_cfg already treats a comma as AND.
                sub, sub_extra = eval_cfg(inner)
                platforms &= sub
                extra += sub_extra
                continue
            union = frozenset()
            for branch in split_top(inner):
                sub, sub_extra = eval_cfg(branch)
                union |= sub
                extra += sub_extra
            platforms &= union
            continue
        atom = ATOM.match(part)
        if not atom:
            extra.append(" ".join(part.split()))
            continue
        resolved = atom_platforms(atom.group(1), atom.group(2))
        if resolved is None:
            extra.append(" ".join(part.split()))
            continue
        platforms &= resolved
    return platforms, extra


def brace_end(clean: str, open_brace: int) -> int:
    depth = 0
    for i in range(open_brace, len(clean)):
        if clean[i] == "{":
            depth += 1
        elif clean[i] == "}":
            depth -= 1
            if depth == 0:
                return i + 1
    return len(clean)


def attribute_blocks(clean: str, raw: str) -> list[dict]:
    """Every run of `#[...]` attributes, with its offsets, names and cfg conditions.

    A run is one or more consecutive attributes; the item after the run is what they apply to.
    `cfg_attr(<plat>, ignore = "...")` is told apart from a plain `#[ignore]`: the first makes a
    test that exists on that platform and is skipped there, the second skips it everywhere and is
    already inventoried by `ignored-tests.py`.
    """
    blocks: list[dict] = []
    n = len(clean)
    i = 0
    while i < n:
        if clean[i] != "#" or not clean.startswith("#[", i):
            i += 1
            continue
        start = i
        names: list[str] = []
        cfgs: list[str] = []
        ignore_if: list[str] = []
        plain_ignore = False
        j = i
        while j < n and clean.startswith("#[", j):
            depth = 0
            k = j
            while k < n:
                ch = clean[k]
                if ch in "[(":
                    depth += 1
                elif ch in "])":
                    depth -= 1
                    if depth == 0:
                        break
                k += 1
            # The offsets come from the blanked text, so an attribute written inside a comment
            # or a string literal is never matched. The content comes from the raw text, because
            # blanking erases the `"macos"` in `cfg(target_os = "macos")` -- positions are
            # preserved between the two, so the slice is the same attribute either way.
            head = ATTR_HEAD.match(raw[j + 2 : k])
            if head:
                name, arg = head.group(1), head.group(2) or ""
                names.append(name)
                if name == "cfg":
                    cfgs.append(arg)
                elif name == "ignore":
                    plain_ignore = True
                elif name == "cfg_attr":
                    pieces = split_top(arg)
                    if len(pieces) >= 2 and re.match(r"^\s*ignore\b", ",".join(pieces[1:])):
                        # The condition says where the test is SKIPPED, which is the complement of
                        # where it runs; keeping it out of `cfgs` is what stops the two from being
                        # read as the same kind of gate.
                        ignore_if.append(pieces[0])
            j = k + 1
            while j < n and clean[j] in " \t\r\n":
                j += 1
        blocks.append(
            {
                "start": start,
                "after": j,
                "names": names,
                "cfgs": cfgs,
                "ignore_if": ignore_if,
                "plain_ignore": plain_ignore,
            }
        )
        i = max(j, start + 1)
    return blocks


def gated_spans(clean: str, blocks) -> list[tuple[frozenset[str], int, int]]:
    """(platforms, from, to) for every cfg'd item, extending over its braces when it has a body.

    An item with a body gates everything inside the matching brace; an item without one (`use`,
    a `mod` declaration, a field) gates only up to its `;`. Without the second rule a
    `#[cfg(unix)] use foo::Bar;` line would appear to gate the rest of the file.
    """
    spans: list[tuple[frozenset[str], int, int]] = []
    for block in blocks:
        cfgs = block["cfgs"]
        if not cfgs:
            continue
        platforms = ALL_PLATFORMS
        for arg in cfgs:
            platforms &= eval_cfg(arg)[0]
        if platforms == ALL_PLATFORMS:
            continue
        after = block["after"]
        brace = clean.find("{", after)
        semi = clean.find(";", after)
        if brace >= 0 and (semi < 0 or brace < semi):
            end = brace_end(clean, brace)
        elif semi >= 0:
            end = semi + 1
        else:
            end = after
        spans.append((platforms, block["start"], end))
    return spans


def crate_of(rel: Path, crate_dirs: frozenset[tuple[str, ...]]) -> str:
    """The package the file belongs to: the nearest ancestor holding a `Cargo.toml`.

    Deriving it from a directory layout instead would read `crates/foo/src/lib.rs` as crate `src`
    the first time the repository grows a one-level member, and the crate column is what the
    summary groups by.
    """
    parts = rel.parts
    for depth in range(len(parts) - 1, 0, -1):
        if parts[:depth] in crate_dirs:
            return parts[depth - 1]
    return parts[0] if parts else "."


def scan_file(raw: str, rel: Path, crate_dirs: frozenset[tuple[str, ...]]) -> list[dict]:
    clean = blank_noise(raw)
    # Same offsets, but string literals survive: the assumption markers have to see
    # `Command::new("chmod")`, and a `chmod` mentioned only in a comment must not count. Built on
    # first need, because most scanned files contain no gated test and the second text pass is not
    # free across a repository this size.
    strings: str | None = None
    blocks = attribute_blocks(clean, raw)
    spans = gated_spans(clean, blocks)
    file_platforms = ALL_PLATFORMS
    file_extra: list[str] = []
    for m in INNER_CFG.finditer(raw):
        # A `#![cfg(...)]` written in a comment is blanked in `clean`, so the same offset holding
        # a `#` there is what makes this match a real inner attribute.
        if clean[m.start()] != "#":
            continue
        platforms, extra = eval_cfg(m.group(1))
        file_platforms &= platforms
        file_extra += extra
    rows: list[dict] = []
    for block in blocks:
        names = block["names"]
        if not (
            any(TEST_ATTR.search(name) for name in names)
            or any(name in OTHER_TEST_ATTR for name in names)
        ):
            continue
        after = block["after"]
        found = FN_NAME.search(clean[after : after + 400])
        if not found:
            continue
        own = ALL_PLATFORMS
        extra = list(file_extra)
        for arg in block["cfgs"]:
            platforms, terms = eval_cfg(arg)
            own &= platforms
            extra += terms
        for span_platforms, span_start, span_end in spans:
            if span_start <= block["start"] < span_end:
                own &= span_platforms
        platforms = file_platforms & own
        if block["ignore_if"]:
            kind = KIND_IGNORE
            for cond in block["ignore_if"]:
                cond_platforms, cond_extra = eval_cfg(cond)
                platforms -= cond_platforms
                extra += cond_extra
        elif platforms != ALL_PLATFORMS and block["plain_ignore"]:
            kind = KIND_GATE_IGNORED
        else:
            kind = KIND_GATE
        assumptions = "-"
        if platforms != ALL_PLATFORMS:
            # Brace counting uses the fully blanked copy, so a `{` inside a string literal cannot
            # open a phantom block; the text is then sliced from the copy that kept strings.
            brace = clean.find("{", after + found.end())
            if 0 <= brace < len(clean) and clean[brace] == "{":
                if strings is None:
                    strings = blank_noise(raw, keep_strings=True)
                end = brace_end(clean, brace)
                assumptions = assumption_label(
                    strings[brace : end + 1], platforms, path_words(rel.as_posix())
                )
        rows.append(
            {
                "kind": kind,
                "crate": crate_of(rel, crate_dirs),
                "file": rel.as_posix(),
                "line": clean.count("\n", 0, block["start"]) + 1,
                "function": found.group(1),
                "runs_on": platforms,
                "extra_cfg": sorted(set(extra)),
                "assumptions": assumptions,
            }
        )
    return rows


def scan(root: Path) -> list[dict]:
    """Every test function in the repository with the platform set it would run on.

    The walk prunes `SKIP_DIRS` on the way down instead of filtering after the fact: this
    repository's `target/` holds hundreds of gigabytes, and a `rglob` that walked it before
    discarding the hits made the gate take minutes on a warm checkout.
    """
    rows: list[dict] = []
    # Two passes: the crate column is the nearest ancestor with a Cargo.toml, and a file may sit
    # in the tree before the directory that declares the package is walked.
    found: list[tuple[Path, Path]] = []
    crate_dirs: set[tuple[str, ...]] = set()
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS)
        if "Cargo.toml" in filenames:
            crate_dirs.add(Path(dirpath).relative_to(root).parts)
        for name in sorted(filenames):
            if name.endswith(".rs"):
                path = Path(dirpath) / name
                found.append((path, path.relative_to(root)))
    crate_set = frozenset(crate_dirs)
    for path, rel in found:
        try:
            raw = path.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        # A file with no platform word anywhere cannot host a platform-gated test, and cannot
        # carry a `#![cfg(...)]` file gate either. Skipping those files is what keeps this a
        # gate that runs in seconds rather than a whole-repository text pass.
        if not PLATFORM_WORD.search(raw):
            continue
        rows += scan_file(raw, rel, crate_set)
    return rows


def ledger_rows(rows: list[dict]) -> list[dict]:
    """The rows that belong in the ledger: the ones some platform does not build."""
    return [r for r in rows if r["runs_on"] != ALL_PLATFORMS]


def runs_on_label(platforms: object) -> str:
    """The `runs_on` spelling, accepting either a scanned platform set or a ledger string."""
    if isinstance(platforms, str):
        return platforms.strip()
    return "+".join(p for p in PLATFORMS if p in platforms)


def extra_label(terms: object) -> str:
    """The non-platform part of a test's gating, in the spelling the ledger stores.

    It is part of a row's identity: tightening `cfg(all(unix, feature = "a"))` to another feature
    changes what the row documents even though the platform set is unchanged.
    """
    if isinstance(terms, str):
        return " ".join(terms.split()) or "-"
    return ";".join(" ".join(t.split()) for t in sorted(set(terms))) or "-"


def key_of(row: dict) -> tuple[str, str, str, str, str, str]:
    """What makes a ledger row the row for a test.

    The line number is deliberately absent: an edit anywhere above a gated test would otherwise
    demand a ledger rewrite that says nothing about the debt, so the line stays a navigation hint
    that `--write-baseline` regenerates and `--check-baseline` does not compare. Everything that
    says what is being hidden is present, including the body's platform assumptions.
    """
    return (
        row["file"],
        row["function"],
        runs_on_label(row["runs_on"]),
        row["kind"],
        extra_label(row["extra_cfg"]),
        row["assumptions"].strip() or "none",
    )


def describe_key(key: tuple[str, str, str, str, str, str]) -> str:
    file, function, runs_on, kind, extra, assumptions = key
    extra = "" if extra == "-" else f" extra_cfg={extra}"
    return (
        f"{file} {function} [{kind}] runs on {runs_on} only{extra} "
        f"assumptions={assumptions}"
    )


def blind_files(rows: list[dict]) -> dict[str, set[str]]:
    """Files with at least one gated test and no test at all that runs on the platform.

    Ungated tests run everywhere, so one ungated test in the file is enough to clear it; that is
    why the caller passes every test row, not just the ledger rows.
    """
    covered: dict[str, set[str]] = {}
    gated_files: set[str] = set()
    for r in rows:
        covered.setdefault(r["file"], set()).update(r["runs_on"])
        if r["runs_on"] != ALL_PLATFORMS:
            gated_files.add(r["file"])
    out = {"windows": set(), "macos": set(), "linux": set()}
    for path, platforms in covered.items():
        if path not in gated_files:
            continue
        for platform in out:
            if platform not in platforms:
                out[platform].add(path)
    return out


def assumption_free(rows: list[dict]) -> list[dict]:
    """Gated tests whose own body shows no assumption about the platform the gate keeps out.

    This is the list the debt note asked to be named: gating that is only a POSIX fixture in
    appearance, and that could be made to run on the other platform. `none` is a claim about the
    test's text, not proof, so the count is budgeted rather than trusted.
    """
    return [r for r in rows if r["kind"] != KIND_IGNORE and r["assumptions"] == "none"]


def render_table(rows: list[dict]) -> str:
    lines = ["\t".join(HEADER)]
    for r in sorted(rows, key=lambda r: (r["file"], r["line"])):
        lines.append(
            "\t".join(
                (
                    r["kind"],
                    r["crate"],
                    r["file"],
                    str(r["line"]),
                    r["function"],
                    runs_on_label(r["runs_on"]),
                    extra_label(r["extra_cfg"]),
                    r["assumptions"],
                    UNREVIEWED,
                )
            )
        )
    return "\n".join(lines)


def read_baseline(path: Path) -> list[dict]:
    rows = []
    header = "\t".join(HEADER)
    for lineno, line in enumerate(path.read_text(encoding="utf-8").split("\n"), 1):
        if not line.strip() or line.startswith("#") or line == header:
            continue
        cols = line.split("\t")
        if len(cols) != len(HEADER):
            raise SystemExit(f"{path}:{lineno}: expected {len(HEADER)} columns, got {len(cols)}")
        rows.append(dict(zip(HEADER, cols)))
    return rows


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--root", type=Path, default=DEFAULT_ROOT)
    ap.add_argument("--table", action="store_true", help="print every ledger row")
    ap.add_argument("--write-baseline", type=Path)
    ap.add_argument("--check-baseline", type=Path)
    ap.add_argument("--max-unreviewed", type=int)
    ap.add_argument("--max-blind-windows", type=int)
    ap.add_argument("--max-blind-macos", type=int)
    ap.add_argument("--max-assumption-free", type=int,
                    help="budget for gated tests whose body shows no platform assumption")
    ap.add_argument("--list-assumption-free", action="store_true",
                    help="print every gated test whose body shows no platform assumption")
    ap.add_argument("--quiet", action="store_true")
    args = ap.parse_args(argv)

    root = args.root.resolve()
    rows = scan(root)
    ledger = ledger_rows(rows)
    gated = [r for r in ledger if r["kind"] != KIND_IGNORE]
    ignores = [r for r in ledger if r["kind"] == KIND_IGNORE]
    both = [r for r in ledger if r["kind"] == KIND_GATE_IGNORED]
    blind = blind_files(rows)
    free = assumption_free(ledger)

    if args.write_baseline:
        args.write_baseline.write_text(render_table(ledger) + "\n", encoding="utf-8")
        print(f"wrote {len(ledger)} rows to {args.write_baseline}")
        return 0

    problems: list[str] = []
    if args.check_baseline:
        # Multiset comparison, like scripts/ci/ignored-tests.py: the same test name can legitimately
        # appear twice in one file (two modules, identical gating), and a ledger must be able to say
        # so without the gate reading the second row as a duplicate.
        live = Counter(key_of(r) for r in ledger)
        first_live: dict[tuple[str, str, str, str, str, str], dict] = {}
        for r in ledger:
            first_live.setdefault(key_of(r), r)
        seen = Counter()
        for row in read_baseline(args.check_baseline):
            key = key_of(row)
            seen[key] += 1
            if live[key] == 0:
                # A rewritten cfg or a renamed test lands here. The row has to be re-derived, not
                # deleted: deleting it must never erase the debt the row describes.
                same = [describe_key(k) for k in live if k[0] == key[0] and k[1] == key[1]]
                hint = f"; the test is now {' / '.join(same)}" if same else "; the test is gone"
                problems.append(
                    f"stale baseline row {row['file']}:{row['line']} {row['function']}{hint}"
                )
            elif seen[key] > live[key]:
                problems.append(f"duplicate baseline row: {describe_key(key)}")
            reason = row["reason"].strip()
            if len(reason) < MIN_REASON:
                problems.append(
                    f"{row['file']}:{row['line']} {row['function']}: reason is {len(reason)} "
                    f"chars, needs >= {MIN_REASON}"
                )
        for key, row in first_live.items():
            if seen[key] < live[key]:
                problems.append(
                    f"unlisted platform-gated test {row['file']}:{row['line']} "
                    f"{row['function']} runs on {runs_on_label(row['runs_on'])} only"
                )
        unreviewed = sum(1 for row in read_baseline(args.check_baseline)
                         if row["reason"].strip() == UNREVIEWED)
        if args.max_unreviewed is not None and unreviewed > args.max_unreviewed:
            problems.append(
                f"{unreviewed} rows still carry the import marker, over the budget of "
                f"{args.max_unreviewed}"
            )
    if args.max_blind_windows is not None and len(blind["windows"]) > args.max_blind_windows:
        problems.append(
            f"{len(blind['windows'])} files have platform-gated tests and nothing that runs on "
            f"Windows, over the budget of {args.max_blind_windows}"
        )
    if args.max_blind_macos is not None and len(blind["macos"]) > args.max_blind_macos:
        problems.append(
            f"{len(blind['macos'])} files have platform-gated tests and nothing that runs on "
            f"macOS, over the budget of {args.max_blind_macos}"
        )
    if args.max_assumption_free is not None and len(free) > args.max_assumption_free:
        # Named here rather than only counted: the point of the number is the list, and a CI log
        # that says "613" tells nobody which gate to delete.
        problems.append(
            f"{len(free)} gated tests show no platform assumption in their body, over the budget "
            f"of {args.max_assumption_free}; these are candidates to un-gate: "
            + ", ".join(f"{r['file']}:{r['line']} {r['function']}" for r in free[:40])
        )

    if not args.quiet:
        by_crate: dict[str, int] = {}
        for r in gated:
            by_crate[r["crate"]] = by_crate.get(r["crate"], 0) + 1
        print(f"platform-gated tests: {len(gated)} in {len({r['file'] for r in gated})} files")
        print(f"platform-conditional #[ignore] (exists there, skipped there): {len(ignores)}")
        print(f"gated and also #[ignore]d everywhere: {len(both)}")
        print(
            f"gated with no platform assumption in the body: {len(free)} in "
            f"{len({r['file'] for r in free})} files"
        )
        print("would compile on:")
        for platform in PLATFORMS:
            n = sum(1 for r in gated if platform in r["runs_on"])
            print(f"  {platform:<11} {n} of {len(gated)}")
        print("files with gated tests and no test that runs on the platform:")
        for platform in ("windows", "macos", "linux"):
            print(f"  {platform:<11} {len(blind[platform])}")
        print("top crates by gated tests:")
        for crate, n in sorted(by_crate.items(), key=lambda kv: (-kv[1], kv[0]))[:12]:
            print(f"  {n:>4}  {crate}")
    if args.list_assumption_free:
        for r in free:
            print(
                f"{r['crate']}\t{r['file']}:{r['line']}\t{r['function']}\t"
                f"{runs_on_label(r['runs_on'])}"
            )
    if args.table:
        print(render_table(ledger))

    for problem in problems:
        print(f"FAIL: {problem}", file=sys.stderr)
    if problems:
        print(f"{len(problems)} problem(s)", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
